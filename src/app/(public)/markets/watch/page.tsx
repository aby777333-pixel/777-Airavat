import Link from "next/link";
import { getMarketStatus, getQuotes } from "@/lib/market";
import { istTime } from "@/lib/format";
import { Notice, PageHeader, SimBadge } from "@/components/ui";
import PageHero from "@/components/site/PageHero";
import { metadataFor, seoFor } from "@/lib/seo";
import { MarketCrumbs, QuoteTable } from "../_shared";

export const metadata = { ...metadataFor("/markets"), title: "Market watch: every NSE instrument with simulated quotes" };

export default async function MarketWatch({ searchParams }: { searchParams: Promise<{ q?: string; segment?: string }> }) {
  const { q = "", segment = "" } = await searchParams;
  const [rows, ms] = await Promise.all([getQuotes(), getMarketStatus()]);
  const needle = q.trim().toUpperCase();
  const list = rows.filter((r) => (!segment || r.segment === segment) && (!needle || r.symbol.includes(needle) || r.name.toUpperCase().includes(needle)));
  return (
    <div className="mx-auto max-w-7xl px-4 py-10 sm:px-6">
      <MarketCrumbs label="Market watch" />
      <PageHero variant="markets" intro={seoFor("/markets").intro}><PageHeader eyebrow="Markets" title="Market watch" subtitle={<>Session <strong>{ms.status}</strong> · updated {istTime(rows[0]?.quote.updated_at)} · <SimBadge /></>} /></PageHero>
      <Notice tone="warn">Prices are generated by the sandbox market engine; they are not exchange data.</Notice>
      <form className="my-4 flex flex-wrap gap-2 text-sm"><input className="input max-w-xs" name="q" defaultValue={q} placeholder="Search symbol or name" aria-label="Search" /><select className="select w-auto" name="segment" defaultValue={segment}><option value="">All segments</option><option value="EQ">Equity</option><option value="INDEX">Indices</option><option value="COMM">Commodity (research)</option><option value="CDS">Currency (research)</option></select><button className="btn btn-ghost">Filter</button><Link className="btn btn-ghost" href="/api/watchlist/export" prefetch={false}>Export CSV</Link></form>
      <QuoteTable rows={list} />
      <p className="mt-3 text-xs text-faint">{list.length} instruments. Signed-in users can import and export watchlists as CSV from the app.</p>
    </div>
  );
}
