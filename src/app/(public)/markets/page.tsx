import PageHero from "@/components/site/PageHero";
import { seoFor, metadataFor } from "@/lib/seo";
import Link from "next/link";
import clsx from "clsx";
import { getMarketStatus, getQuotes } from "@/lib/market";
import { changeOf, integer, istTime, pct, price } from "@/lib/format";
import { PageHeader, SimBadge, Notice } from "@/components/ui";

export const metadata = { ...metadataFor("/markets") };

export default async function Markets() {
  const [rows, ms] = await Promise.all([getQuotes(), getMarketStatus()]);
  const eq = rows.filter((r) => r.segment === "EQ").map((r) => ({ ...r, ...changeOf(r.quote.ltp, r.quote.prev_close) }));
  const sectors = new Map<string, { n: number; sum: number }>();
  for (const r of eq) { const s = sectors.get(r.sector ?? "Other") ?? { n: 0, sum: 0 }; s.n++; s.sum += r.changePct; sectors.set(r.sector ?? "Other", s); }
  const breadth = { up: eq.filter((r) => r.change > 0).length, down: eq.filter((r) => r.change < 0).length, flat: eq.filter((r) => r.change === 0).length };
  const latest = rows[0]?.quote.updated_at;

  return (
    <div className="mx-auto max-w-7xl px-4 py-12 sm:px-6">
      <PageHero variant="markets" intro={seoFor("/markets").intro}><PageHeader eyebrow="Markets" title="Market overview" subtitle={<>Session <strong>{ms.status}</strong> · Last update {istTime(latest)} · Source: <SimBadge /></>} /></PageHero>
      <Notice tone="warn">Prices on this page are generated by AIRAVAT&apos;s sandbox market engine. They are not NSE or BSE data and must not be used for any real decision.</Notice>

      <div className="mt-6 grid gap-4 md:grid-cols-3">
        <div className="glass p-5">
          <div className="text-xs uppercase tracking-wider text-muted">Breadth</div>
          <div className="mt-2 flex gap-4 text-sm">
            <span className="text-profit">▲ {breadth.up}</span><span className="text-loss">▼ {breadth.down}</span><span className="text-muted">= {breadth.flat}</span>
          </div>
          <div className="mt-3 flex h-2 overflow-hidden rounded-full bg-bg">
            <div className="bg-profit" style={{ width: `${(breadth.up / eq.length) * 100}%` }} />
            <div className="bg-loss" style={{ width: `${(breadth.down / eq.length) * 100}%` }} />
          </div>
        </div>
        <div className="glass p-5 md:col-span-2">
          <div className="text-xs uppercase tracking-wider text-muted">Sector heatmap (avg % change)</div>
          <div className="mt-3 grid grid-cols-3 gap-2 sm:grid-cols-5">
            {[...sectors.entries()].sort((a, b) => b[1].sum / b[1].n - a[1].sum / a[1].n).map(([name, s]) => {
              const avg = s.sum / s.n;
              return (
                <div key={name} className={clsx("rounded-lg p-2 text-xs", avg >= 0 ? "bg-profit/15 text-profit" : "bg-loss/15 text-loss")} style={{ opacity: 0.5 + Math.min(Math.abs(avg), 2) / 4 }}>
                  <div className="truncate font-medium">{name}</div>
                  <div className="tnum">{pct(avg)}</div>
                </div>
              );
            })}
          </div>
        </div>
      </div>

      <div className="glass mt-6 overflow-x-auto p-2">
        <table className="table">
          <thead>
            <tr><th>Symbol</th><th>Name</th><th>Sector</th><th className="num">LTP</th><th className="num">Change</th><th className="num">%</th><th className="num">Open</th><th className="num">High</th><th className="num">Low</th><th className="num">Volume</th></tr>
          </thead>
          <tbody>
            {rows.map((r) => {
              const c = changeOf(r.quote.ltp, r.quote.prev_close);
              return (
                <tr key={r.symbol}>
                  <td><Link className="font-semibold hover:text-accent" href={`/markets/${encodeURIComponent(r.symbol)}`}>{r.symbol}</Link>{r.segment === "INDEX" && <span className="ml-2 badge">Index</span>}</td>
                  <td className="text-muted">{r.name}</td>
                  <td className="text-muted">{r.sector}</td>
                  <td className="num">{price(r.quote.ltp)}</td>
                  <td className={clsx("num", c.change >= 0 ? "text-profit" : "text-loss")}>{price(c.change)}</td>
                  <td className={clsx("num", c.change >= 0 ? "text-profit" : "text-loss")}>{pct(c.changePct)}</td>
                  <td className="num text-muted">{price(r.quote.open)}</td>
                  <td className="num text-muted">{price(r.quote.high)}</td>
                  <td className="num text-muted">{price(r.quote.low)}</td>
                  <td className="num text-muted">{integer(r.quote.volume)}</td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
    </div>
  );
}
